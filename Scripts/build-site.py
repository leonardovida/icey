"""Builds Icey's website and docs/upstream-issues.md from docs/issues.json.

Usage:
  Scripts/build-site.py --out build/site     # website, into build/site
  Scripts/build-site.py --docs               # regenerate docs/upstream-issues.md
  Scripts/build-site.py --check              # fail if docs/upstream-issues.md is stale

The website reads the published releases from the GitHub API (set GITHUB_TOKEN
to avoid rate limits), so its download button always points at the latest
release's DMG, and fixes only link to releases that exist. Without network
access it falls back to the releases page. Uses only the Python standard library.
"""


def tag_label(tag):
    return tag[1:] if tag.startswith("v") else tag


# MARK: - Releases


def fetch_releases():
    """Returns the published, non-draft releases, newest first, or None offline."""
    req = urllib.request.Request(
        f"https://api.github.com/repos/{REPO}/releases?per_page=100",
        headers={"Accept": "application/vnd.github+json", "User-Agent": "icey-site"},
    )
    token = os.environ.get("GITHUB_TOKEN") or os.environ.get("GH_TOKEN")
    if token:
        req.add_header("Authorization", f"Bearer {token}")
    try:
        with urllib.request.urlopen(req, timeout=20) as resp:
            releases = json.load(resp)
    except Exception as error:  # noqa: BLE001 - any failure means "offline"
        print(f"warning: couldn't read releases ({error}); using fallback links", file=sys.stderr)
        return None
    return [r for r in releases if not r.get("draft")]


def latest_release(releases):
    """The release GitHub calls "latest": the newest one that isn't a prerelease."""
    for r in releases or []:
        if not r.get("prerelease"):
            dmg = next((a for a in r.get("assets", []) if a["name"].endswith(".dmg")), None)
            return {
                "tag": r["tag_name"],
                "version": tag_label(r["tag_name"]),
                "date": (r.get("published_at") or "")[:10],
                "url": r["html_url"],
                "dmg": dmg["browser_download_url"] if dmg else r["html_url"],
                "dmg_name": dmg["name"] if dmg else None,
            }
    return None


# MARK: - docs/upstream-issues.md


def md_issue(n, kind="issues"):
    return f"[#{n}]({UPSTREAM}/{kind}/{n})"


def md_cell(text):
    return text.replace("|", "\\|")


def md_release(tag):
    if not tag:
        return "Next release"
    return f"[{tag_label(tag)}]({GH}/releases/tag/{tag})"


def build_docs(data):
    issues = data["issues"]
    by = {s: [i for i in issues if i["status"] == s] for s in STATUS_ORDER}
    out = [
        "<!-- Generated by Scripts/build-site.py from docs/issues.json. Edit that file, then run Scripts/build-site.py --docs. -->",
        "",
        "# Upstream Ice issues and their status in Icey",
        "",
        f"This page maps bugs reported against [Ice]({UPSTREAM}) (jordanbaird/Ice) to their status in Icey. "
        "If you hit one of these in Ice, [install Icey](../README.md#install) instead. Icey replaces Ice and keeps your settings.",
        "",
        f"Each fix is described in the [release]({GH}/releases) that ships it, and on [Icey's website]({SITE_URL}/fixes/). "
        f"Issue titles are quoted as they appear upstream. To report a problem that isn't listed, [open an issue in Icey]({GH}/issues/new/choose).",
        "",
        f"## Fixed in Icey ({len(by['fixed'])})",
        "",
        "| Upstream issue | Problem | Fixed in |",
        "|---|---|---|",
    ]
    for i in by["fixed"]:
        note = f" ({i['note']})" if i.get("note") else ""
        out.append(f"| {md_issue(i['number'])} | {md_cell(i['headline'])} | {md_release(i['fixed_in'])}{md_cell(note)} |")
    sections = [
        ("partial", "Partly addressed", "These have a fix that couldn't be confirmed yet, or that covers part of the report."),
        ("open", "Open in Icey too", f"These need a reproduction or more information. If you can reproduce one in Icey, please [open an issue]({GH}/issues/new/choose) with your macOS version and steps."),
        ("not-a-bug", "Not a bug in Ice or Icey", None),
        ("feature", "Feature requests", None),
    ]
    for status, heading, intro in sections:
        rows = by[status]
        if not rows:
            continue
        out += ["", f"## {heading}", ""]
        if intro:
            out += [intro, ""]
        if status == "partial":
            out += ["| Upstream issue | Problem | Status |", "|---|---|---|"]
            for i in rows:
                status_text = i["fix"] + (f" {i['note']}" if i.get("note") else "")
                out.append(f"| {md_issue(i['number'])} | {md_cell(i['headline'])} | {md_cell(status_text)} |")
        elif status == "open":
            out += ["| Upstream issue | Problem |", "|---|---|"]
            for i in rows:
                out.append(f"| {md_issue(i['number'])} | {md_cell(i['headline'])} |")
        else:
            label = "What to do" if status == "not-a-bug" else "Status"
            out += [f"| Upstream issue | Title | {label} |", "|---|---|---|"]
            for i in rows:
                out.append(f"| {md_issue(i['number'])} | {md_cell(i['title'])} | {md_cell(i['fix'])} |")
    out += [
        "",
        "## Upstream pull requests included in Icey",
        "",
        "Icey includes these community pull requests that upstream Ice has not merged. Their authors are credited in the commits.",
        "",
    ]
    for p in data.get("upstream_prs", []):
        refs = ", ".join(md_issue(n, "pull" if p["kind"] == "pull" else "issues") for n in p["numbers"])
        out.append(f"- {refs}: {p['summary']}")
    return "\n".join(out) + "\n"


